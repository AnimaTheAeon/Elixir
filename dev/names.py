import asyncio
from playwright.async_api import async_playwright
errors=[]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--no-sandbox"])
        pg = await b.new_page(viewport={"width": 1280, "height": 900})
        pg.on("pageerror", lambda e: errors.append("pageerror: " + str(e)))
        pg.on("console", lambda m: errors.append("console: " + m.text) if m.type == "error" else None)
        await pg.goto("http://127.0.0.1:7810/")
        await pg.wait_for_selector("#splash", state="detached", timeout=12000)
        await pg.evaluate("go('config')")
        await pg.wait_for_timeout(800)
        await pg.locator("#names").scroll_into_view_if_needed()
        await pg.screenshot(path="/tmp/ex/shots/n1-midgar.png")
        print("note:", await pg.inner_text("#naming-note"))
        print(await pg.inner_text("#naming-examples"))
        await pg.select_option("#naming-preset", "plex")
        await pg.wait_for_timeout(1200)
        print("--plex:", await pg.inner_text("#naming-examples"))
        await pg.fill("[data-key='episode_naming.standard']", "{Series Title} {season}x{episode:00} {Episode Title}")
        await pg.wait_for_timeout(500)
        print("--typed:", (await pg.inner_text("#naming-examples")).splitlines()[1])
        await pg.locator("[data-key='episode_naming.standard']").dispatch_event("change")
        await pg.wait_for_timeout(1200)
        print("preset now:", await pg.input_value("#naming-preset"))
        await pg.locator("#names").scroll_into_view_if_needed()
        await pg.screenshot(path="/tmp/ex/shots/n2-custom.png")
        await pg.evaluate("go('auto')")
        await pg.wait_for_timeout(800)
        await pg.screenshot(path="/tmp/ex/shots/n3-auto.png")
        await b.close()
asyncio.run(main())
print("errors:", errors)
